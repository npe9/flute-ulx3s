#!/usr/bin/env python3
"""Generate test/bk_test.S: whole-core Zb*/Zk* test for the strict-BRAM sim and hardware.

Every XBox op on edge/random operands (rd = a2 from a0/a1), plus dependent chains (an XBox
result feeding the next XBox op, an ALU op and a load base -- the stage2 bypass), an XBox op
with rd = x0, and misa.B.  Expected values come from Sail (riscv_sim_RV32) running the same
instruction sequence.  UART protocol as mul_test.S: 'T', 'M <id> <exp> <got>' per mismatch, 'D'.
usage: gen_bk_test.py [--n N] [--seed S]"""
import argparse, os, random, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xbox_vs_sail import OPS, EDGE, enc, SAIL

def body(cs):
    """Instruction list; each check is ('CHK', id) after the value under test is in a2."""
    B = []
    for i, (n, v1, v2, imm) in enumerate(cs):
        B += [f"li a0, {v1:#x}", f"li a1, {v2:#x}", f".word 0x{enc(n, imm):08x}  # {n}", ("CHK", i)]
    k = len(cs)
    # chains through the bypass: xbox -> xbox -> xbox, xbox -> alu, xbox -> load base
    w = lambda n, imm=0: f".word 0x{enc(n, imm):08x}  # {n}"
    B += ["li a0, 0x13579bdf", "li a1, 0x2468ace0", w("clmul"), "mv a0, a2", w("aes32esmi", 2), "mv a0, a2",
          w("sha256sig0"), ("CHK", k)]
    B += ["li a0, 0x0f0f1234", w("rev8"), "addi a2, a2, 1", ("CHK", k + 1)]
    B += ["li a0, 2", "la a1, data", w("sh2add"), "lw a2, 0(a2)", ("CHK", k + 2)]   # a2 = (a0<<2) + a1 -> data[2]
    B += ["li a2, 0x55", "li a0, 0x12345678", ".word 0x{:08x}  # rev8 x0".format(enc("rev8", 0) & ~(31 << 7)), ("CHK", k + 3)]
    B += ["csrr a2, misa", "andi a2, a2, 2", ("CHK", k + 4)]   # misa.B (Sail's misa has S, Flute's may not)
    return B, k + 5

def sail_prog(B, nchk):
    L = [".section .text.init", ".globl _start", "_start:", "  la s1, begin_signature"]
    for x in B:
        L += ["  sw a2, 0(s1)", "  addi s1, s1, 4"] if isinstance(x, tuple) else ["  " + x]
    L += ["  li t0, 1", "  la t1, tohost", "  sw t0, 0(t1)", "1: j 1b", ".section .data", ".align 6",
          ".globl tohost", "tohost: .dword 0", ".globl fromhost", "fromhost: .dword 0", ".align 4",
          "data: .word 0x11111111, 0x22222222, 0xc0ffee33, 0x44444444",
          ".align 4", ".globl begin_signature", "begin_signature:", f"  .fill {nchk}, 4, 0xdeadbeef",
          ".globl end_signature", "end_signature:", ""]
    return "\n".join(L)

HEAD = """# Bare-metal Zba/Zbb/Zbc/Zbs + Zbkb/Zbkx/Zkne/Zknd/Zknh test (XBox integration gate).
# GENERATED by test/xbox/gen_bk_test.py from Sail (riscv_sim_RV32); do not edit.
# {n} op checks ({per} per op, {nops} ops) + bypass chains + rd=x0 + misa.
# UART: 'T', 'M <id> <exp> <got>' per mismatch, 'D'.
    .section .text
    .globl _start
    .option norvc
_start:
    li   sp, 0x81000000
    li   s0, 0xC0000000
    li   t0, 'T'
    sw   t0, 0(s0)
"""
TAIL = """    li   t0, 'D'
    sw   t0, 0(s0)
9:  wfi
    j    9b

# chk: a2 = got, t0 = expected, s4 = id
chk:
    beq  a2, t0, 1f
    mv   s5, ra
    li   t2, 'M'
    sw   t2, 0(s0)
    mv   a1, s4
    jal  ra, puthex
    mv   a1, t0
    jal  ra, puthex
    mv   a1, a2
    jal  ra, puthex
    mv   ra, s5
1:  ret

puthex:
    li   t3, 8
    li   t4, 28
ph1: srl  t5, a1, t4
    andi t5, t5, 0xf
    li   t6, 10
    blt  t5, t6, ph2
    addi t5, t5, 'a' - 10
    j    ph3
ph2: addi t5, t5, '0'
ph3: sw   t5, 0(s0)
    addi t3, t3, -1
    addi t4, t4, -4
    bgez t4, ph1
    li   t5, 13
    sw   t5, 0(s0)
    li   t5, 10
    sw   t5, 0(s0)
    ret

    .align 4
data: .word 0x11111111, 0x22222222, 0xc0ffee33, 0x44444444
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=6)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    rnd = random.Random(a.seed)
    pick = lambda: rnd.choice(EDGE) if rnd.random() < 0.4 else rnd.getrandbits(32)
    cs = [(n, pick(), pick(), rnd.getrandbits(5)) for n in OPS for _ in range(a.n)]
    B, nchk = body(cs)
    work = tempfile.mkdtemp(prefix="bk_")
    open(f"{work}/t.S", "w").write(sail_prog(B, nchk))
    open(f"{work}/l.ld", "w").write("OUTPUT_ARCH(riscv)\nENTRY(_start)\nSECTIONS {\n . = 0x80000000;\n"
                                    " .text.init : { *(.text.init) }\n . = ALIGN(0x1000);\n .data : { *(.data) }\n}\n")
    subprocess.run(["riscv64-unknown-elf-gcc", "-march=rv32imac_zicsr", "-mabi=ilp32", "-nostdlib", "-nostartfiles",
                    "-T", f"{work}/l.ld", "-o", f"{work}/t.elf", f"{work}/t.S"], check=True)
    subprocess.run([SAIL, "-V", "-l", "5000000", "--test-signature", f"{work}/t.sig", f"{work}/t.elf"], capture_output=True)
    ref = [int(x, 16) for x in open(f"{work}/t.sig").read().split()]
    assert len(ref) == nchk and 0xdeadbeef not in ref[-5:], (len(ref), nchk, [hex(x) for x in ref[-5:]])
    # misa.B: this Sail predates misa.B (reserved, reads 0); ratified B (2024) defines it, Flute sets it
    ref[-1] = 2
    out = [HEAD.format(n=len(cs), per=a.n, nops=len(OPS))]
    for x in B:
        if isinstance(x, tuple):
            i = x[1]
            out += [f"    li   t0, {ref[i]:#010x}", f"    li   s4, {i:#x}", "    jal  ra, chk"]
        else:
            out.append("    " + x)
    out.append(TAIL)
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bk_test.S")
    open(dst, "w").write("\n".join(out))
    print(f"wrote {os.path.normpath(dst)}: {nchk} checks; misa.B expected set")

if __name__ == "__main__":
    main()
