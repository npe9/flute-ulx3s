#!/usr/bin/env python3
"""formal/sw/rocq/gen_code.py: the code a tier-3 theorem is about, taken from the ELF itself.

   gen_code.py <elf> <out.v> <symbol>...

Writes, for each function symbol, `Definition code_<symbol> : list (Z * mword 16)` -- its
halfwords at their addresses, read from the ELF's bytes (pyelftools-free: `nm` for the symbol
range, `objcopy -O binary` for the bytes) -- plus the ELF's md5, so a theorem names exactly the
binary it was proved for."""
import hashlib, subprocess, sys, tempfile

elf, out, syms = sys.argv[1], sys.argv[2], sys.argv[3:]
nm = subprocess.run(["riscv64-unknown-elf-nm", "-S", elf], capture_output=True, text=True, check=True).stdout
table = {}
for line in nm.splitlines():
    f = line.split()
    if len(f) == 4 and f[2] in "tT":
        table[f[3]] = (int(f[0], 16), int(f[1], 16))
with tempfile.NamedTemporaryFile(suffix=".bin") as t:
    subprocess.run(["riscv64-unknown-elf-objcopy", "-O", "binary", "-j", ".text", elf, t.name], check=True)
    img = open(t.name, "rb").read()
hdr = subprocess.run(["riscv64-unknown-elf-objdump", "-h", elf], capture_output=True, text=True, check=True).stdout
text_base = next(int(l.split()[3], 16) for l in hdr.splitlines() if l.split()[1:2] == [".text"])
md5 = hashlib.md5(open(elf, "rb").read()).hexdigest()
with open(out, "w") as o:
    o.write(f"(* generated by formal/sw/rocq/gen_code.py from {elf.split('/')[-1]} (md5 {md5}) *)\n")
    o.write("From stdpp Require Import base list.\nRequire Import SailStdpp.Base.\nOpen Scope Z.\n\n")
    o.write(f'Definition elf_md5 := "{md5}"%string.\n\n')
    for s in syms:
        a, n = table[s]
        hw = []
        for off in range(0, n, 2):
            p = a + off - text_base
            hw.append((a + off, img[p] | img[p + 1] << 8))
        o.write(f"Definition code_{s} : list (Z * mword 16) := [\n")
        o.write(";\n".join(f'  (0x{ad:08X}, Ox"{v:04X}")' for ad, v in hw))
        o.write("].\n\n")
print(f"{out}: {', '.join(syms)} from {elf} (md5 {md5})")
