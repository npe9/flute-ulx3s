(* formal/sw/rocq/support/riscv_extras.v: the hand-written support sail-riscv's generated Rocq
   model (af5c2f2, generated by sail 0.20.2) imports, rewritten for coq-sail-stdpp 0.20.2 and
   Rocq 9.0 (sail-riscv's own handwritten_support/riscv_extras.v targets the older bbv-based
   prompt monad).  Only what the generated RV32 model uses: the memory accesses go through the
   concurrency interface (sail_mem_read / sail_mem_write), not through definitions here. *)
From stdpp Require Import base.
Require Import SailStdpp.Base.
Require Import SailStdpp.ConcurrencyInterfaceTypes.
Require Import SailStdpp.ConcurrencyInterface.
Require Import SailStdpp.ConcurrencyInterfaceBuiltins.
Require Import riscv_types.
Import Defs.
Open Scope Z.

(* a nondeterministic choice from a non-empty list (the model's internal_pick) *)
Definition internal_pick {A} (vs : list A) : M A := choose_from_list "internal_pick" vs.

Definition shift_bits_left {a b} (v : mword a) (n : mword b) : mword a :=
  shiftl v (int_of_mword false n).
Definition shift_bits_right {a b} (v : mword a) (n : mword b) : mword a :=
  shiftr v (int_of_mword false n).
Definition shift_bits_right_arith {a b} (v : mword a) (n : mword b) : mword a :=
  arith_shiftr v (int_of_mword false n).

Definition print_bits {n} (msg : string) (bs : mword n) : unit := prerr_endline (msg ++ string_of_bits bs).

