(* The platform (bound for Rocq by formal/sw/rocq/soc-coq.patch), from the SoC map
   (Flute/src_Testbench/SoC/SoC_Map.bsv): boot ROM 0x1000 (4 KB), SDRAM 0x80000000 (32 MB),
   CLINT 0x02000000 (48 KB).  The device window 0xC0000000-0xC1FFFFFF is in within_phys_mem
   (the patch), so device accesses are memory events for the proof's environment.  No HTIF:
   tohost parked outside the map, as formal/sw/sail does.  Misaligned accesses trap (Flute). *)
Definition plat_rom_base (_ : unit) : mword 32 := Ox"00001000".
Definition plat_rom_size (_ : unit) : mword 32 := Ox"00001000".
Definition plat_ram_base (_ : unit) : mword 32 := Ox"80000000".
Definition plat_ram_size (_ : unit) : mword 32 := Ox"02000000".
Definition plat_clint_base (_ : unit) : mword 32 := Ox"02000000".
Definition plat_clint_size (_ : unit) : mword 32 := Ox"0000C000".
Definition plat_htif_tohost (_ : unit) : mword 32 := Ox"BFFFFFF0".
Definition plat_enable_dirty_update (_ : unit) : bool := false.
Definition plat_enable_misaligned_access (_ : unit) : bool := false.
Definition plat_mtval_has_illegal_inst_bits (_ : unit) : bool := false.
Definition plat_term_write (_ : mword 8) : unit := tt.
