#!/usr/bin/env python3
"""Generate deb_fvip_top.sv from the Deburster's port list (yosys write_json of mkAXI4_Deburster_A)."""
import json, sys
m = json.load(open(sys.argv[1]))['modules']['mkAXI4_Deburster_A']['ports']
ins = [(n, len(p['bits'])) for n, p in m.items() if p['direction'] == 'input' and n not in ('CLK', 'RST_N')]
outs = [(n, len(p['bits'])) for n, p in m.items() if p['direction'] == 'output']
w = lambda b: f"[{b-1}:0] " if b > 1 else ""
SIGS = ["AWID","AWADDR","AWREGION","AWLEN","AWSIZE","AWBURST","AWLOCK","AWCACHE","AWPROT","AWQOS","AWVALID","AWREADY",
        "WDATA","WSTRB","WLAST","WVALID","WREADY","BID","BRESP","BVALID","BREADY",
        "ARID","ARADDR","ARREGION","ARLEN","ARSIZE","ARBURST","ARLOCK","ARCACHE","ARPROT","ARQOS","ARVALID","ARREADY",
        "RID","RDATA","RRESP","RLAST","RVALID","RREADY"]
TIE = "4'h0"
def chk(name, pre, agent, maxlen, bursts):
    conn = []
    for S in SIGS:
        s = f"{pre}_{S.lower()}"
        conn.append(f".{S}({s if s in m else TIE})")
    conn += [f".{U}(1'b0)" for U in ["AWUSER", "WUSER", "BUSER", "ARUSER", "RUSER"]]
    return (f"""  amba_axi4_protocol_checker
    #('{{ID_WIDTH: 4, ADDRESS_WIDTH: 64, DATA_WIDTH: 64,
        AWUSER_WIDTH: 1, WUSER_WIDTH: 1, BUSER_WIDTH: 1, ARUSER_WIDTH: 1, RUSER_WIDTH: 1,
        MAX_WR_BURSTS: {bursts}, MAX_RD_BURSTS: {bursts}, MAX_WR_LENGTH: {maxlen}, MAX_RD_LENGTH: {maxlen},
        MAXWAIT: 15,
        VERIFY_AGENT_TYPE: amba_axi4_protocol_checker_pkg::{agent},
        PROTOCOL_TYPE: amba_axi4_protocol_checker_pkg::AXI4FULL,
        INTERFACE_REQS: 1, ENABLE_COVER: 1, ENABLE_XPROP: 0, ARM_RECOMMENDED: 0, CHECK_PARAMETERS: 1,
        OPTIONAL_WSTRB: 1, FULL_WR_STRB: 0, OPTIONAL_RESET: 0, EXCLUSIVE_ACCESS: 0, OPTIONAL_LP: 0}})
  {name} (.ACLK(CLK), .ARESETn(RST_N),
    """ + ",\n    ".join(conn) + ");\n")
missing = [s for s in ['from_master_awregion', 'from_master_arregion', 'to_slave_awregion', 'to_slave_arregion'] if s not in m]
out = f"""// AXI4 protocol check of AXI4_Deburster with the YosysHQ FVIP (generated by gen.py; see ../README.md).
// from_master side: DESTINATION agent, bursts up to 256 beats.
// to_slave side:    SOURCE agent with MAX_*_LENGTH = 1, so "the Deburster emits only single beats" is an assert.
// Absent ports tied off: {', '.join(missing) or 'none'}.
// Define REACH to turn the reachability witnesses into asserts that must FAIL.
`default_nettype none
module deb_fvip_top (
  input wire CLK,
""" + ",\n".join(f"  input wire {w(b)}{n}" for n, b in ins) + "\n);\n"
out += """  reg rst_done = 1'b0;  // zero init: ic3 -init-zero zeroes every register
  always @(posedge CLK) rst_done <= 1'b1;
  wire RST_N = rst_done;
"""
out += "".join(f"  wire {w(b)}{n};\n" for n, b in outs)
out += """  // BSV method protocol; the Deburster's reset method is boot-time only.
  always @* assume (!EN_reset);

  mkAXI4_Deburster_A dut (.*);

  // Environment facts about Flute's masters:
  //  - every master drives fabric_default_lock (no exclusive accesses);
  //  - at most 4 write bursts outstanding (the bound the DESTINATION scoreboard relies on; a
  //    paired SOURCE checker would supply it as cp_no_overflow_no_dead_end).
  always @* assume (!from_master_awlock && !from_master_arlock);
  reg [3:0] wr_out = 0;
  always @(posedge CLK)
    if (!RST_N) wr_out <= 0;
    else wr_out <= wr_out + (from_master_awvalid && from_master_awready) - (from_master_bvalid && from_master_bready);
  always @* assume (!(wr_out >= 4 && from_master_awvalid));

  // Downstream slaves in this SoC (Boot_ROM, Mem_Controller) respond in issue order. The Deburster
  // depends on it: rl_wr_resp_slave_to_master counts B beats against f_w_awlen.first and forwards the
  // last beat's BID, so a slave that reorders across IDs (legal AXI) makes it return a wrong/duplicate
  // BID upstream (found by this harness: m_chk ap_data_integrity_out_of_order @10). Assumed here.
  reg [3:0] aw_q [0:15]; reg [3:0] aw_h = 0, aw_t = 0;
  reg [3:0] ar_q [0:15]; reg [3:0] ar_h = 0, ar_t = 0;
  always @(posedge CLK)
    if (!RST_N) begin aw_h <= 0; aw_t <= 0; ar_h <= 0; ar_t <= 0; end
    else begin
      if (to_slave_awvalid && to_slave_awready) begin aw_q[aw_t] <= to_slave_awid; aw_t <= aw_t + 1; end
      if (to_slave_bvalid && to_slave_bready) aw_h <= aw_h + 1;
      if (to_slave_arvalid && to_slave_arready) begin ar_q[ar_t] <= to_slave_arid; ar_t <= ar_t + 1; end
      if (to_slave_rvalid && to_slave_rready && to_slave_rlast) ar_h <= ar_h + 1;
    end
  always @* begin
    assume (!to_slave_bvalid || (aw_h != aw_t && to_slave_bid == aw_q[aw_h]));
    assume (!to_slave_rvalid || (ar_h != ar_t && to_slave_rid == ar_q[ar_h]));
  end

"""
out += chk("m_chk", "from_master", "DESTINATION", 256, 4)
out += "\n" + chk("s_chk", "to_slave", "SOURCE", 1, 16)
out += """
`ifdef REACH
  always @(posedge CLK) if (RST_N) begin
    reach_s_aw:    assert (!(to_slave_awvalid && to_slave_awready));
    reach_s_ar:    assert (!(to_slave_arvalid && to_slave_arready));
    reach_m_b:     assert (!(from_master_bvalid && from_master_bready));
    reach_m_rlast: assert (!(from_master_rvalid && from_master_rready && from_master_rlast));
    reach_m_burst: assert (!(from_master_arvalid && from_master_arready && from_master_arlen != 0));
    reach_m_r2:    assert (!(from_master_rvalid && from_master_rready && !from_master_rlast));
  end
`endif
endmodule
`default_nettype wire
"""
open('deb_fvip_top.sv', 'w').write(out)
print(len(ins), "inputs", len(outs), "outputs; tied off:", missing)
